package agents

import (
	"strconv"
	"strings"
)

func mockCounterRTL(width int) string {
	template := `// Generated by the SV multi-agent MVP (mock mode).
module counter #(
    parameter int WIDTH = __WIDTH__
) (
    input  logic             clk,
    input  logic             rst,
    input  logic             en,
    output logic [WIDTH-1:0] count
);

    always_ff @(posedge clk) begin
        if (rst) begin
            count <= '0;
        end else if (en) begin
            count <= count + 1'b1;
        end
    end

endmodule
`
	return replaceWidth(template, width)
}

func mockCounterTB(width int) string {
	template := `// Generated self-checking testbench (mock mode).
module tb;
    localparam int WIDTH = __WIDTH__;

    logic clk = 1'b0;
    logic rst = 1'b0;
    logic en  = 1'b0;
    logic [WIDTH-1:0] count;
    logic [WIDTH-1:0] expected = '0;

    integer mismatches = 0;
    integer samples = 0;
    time first_fail_time = 0;
    string first_fail_sig = "count";

    always #5 clk = ~clk;

    counter #(.WIDTH(WIDTH)) dut (
        .clk(clk),
        .rst(rst),
        .en(en),
        .count(count)
    );

    // Reference model mirroring the design contract.
    always_ff @(posedge clk) begin
        if (rst) begin
            expected <= '0;
        end else if (en) begin
            expected <= expected + 1'b1;
        end
    end

    task automatic check_count();
        samples = samples + 1;
        if (count !== expected) begin
            mismatches = mismatches + 1;
            if (mismatches == 1) begin
                first_fail_time = $time;
            end
        end
    endtask

    initial begin
        $dumpfile("wave.vcd");
        $dumpvars(0, dut);

        // Synchronous reset.
        rst = 1'b1;
        en  = 1'b0;
        @(posedge clk); #1;
        check_count();

        // Increment while enabled.
        rst = 1'b0;
        en  = 1'b1;
        repeat (5) begin
            @(posedge clk); #1;
            check_count();
        end

        // Hold while disabled.
        en = 1'b0;
        repeat (2) begin
            @(posedge clk); #1;
            check_count();
        end

        // Reset has priority over enable.
        rst = 1'b1;
        en  = 1'b1;
        @(posedge clk); #1;
        check_count();

        $display("Mismatches: %0d in %0d samples", mismatches, samples);
        if (mismatches == 0) begin
            $display("SIMULATION PASSED");
        end else begin
            $display("SIMULATION FAILED - %0d MISMATCHES DETECTED, FIRST AT TIME %0d", mismatches, first_fail_time);
            $display("Hint: Output '%s' has %0d mismatches. First mismatch occurred at time %0d.", first_fail_sig, mismatches, first_fail_time);
        end
        $finish;
    end
endmodule
`
	return replaceWidth(template, width)
}

func replaceWidth(template string, width int) string {
	return strings.ReplaceAll(template, "__WIDTH__", strconv.Itoa(width))
}
